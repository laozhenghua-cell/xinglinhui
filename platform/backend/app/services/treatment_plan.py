def build_treatment_plan(disease_type: str, syndrome: Dict[str, Any], symptoms: Dict[str, Any]) -> Dict[str, Any]:
    pathway = DISEASE_PATHWAYS.get(disease_type)
    if not pathway:
        return {
            "supported": False,
            "message": "当前资料未建立该病种的原著治疗路径，请转专科人工辨证。",
            "source": SOURCE,
        }

    insufficient = bool(syndrome.get("insufficient_data"))
    plan = {
        "supported": True,
        "status": "candidate" if insufficient else "clinician_review_required",
        "goals": pathway["goals"],
        "internal_treatment": {
            "syndrome": syndrome.get("syndrome_name"),
            "principle": syndrome.get("treatment_principle"),
            "formulas": [] if insufficient else syndrome.get("recommended_formulas", []),
            "note": "资料不足时不生成方剂建议。所有方药须经执业医师结合患者年龄、妊娠、肝肾功能、过敏史及合并用药审核。",
        },
        "local_care": pathway["local_care"],
        "specialist_treatment": pathway["specialist"],
        "follow_up": pathway["follow_up"],
        "course_and_review": {
            "initial_course": pathway["follow_up"][0],
            "review_points": ["主症变化：出血、疼痛、肿胀、脱出或排脓", "复核舌脉、大便及药物不良反应", "疗效不足或出现风险征象时调整方案或转专科"],
        },
        "daily_care": pathway["care"],
        "red_flags": pathway["red_flags"],
        "source": SOURCE,
        "source_sections": pathway["source_sections"],
        "clinical_notice": "本方案用于辅助临床决策，不能替代面诊、指检/肛门镜检查、必要的影像或病理检查。",
        "original_knowledge": syndrome.get("original_knowledge", {}),
    }
    return plan
