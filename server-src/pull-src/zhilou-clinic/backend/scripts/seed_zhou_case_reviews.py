async def main():
    async with AsyncSessionLocal() as session:
        print("=" * 64)
        print("《医案述评》4 案完整结构化录入")
        print("=" * 64)
        for data in CASES:
            if isinstance(data.get("key_points"), list):
                data["key_points"] = "\n".join(data["key_points"])
            r = await session.execute(select(MedicalCase).where(MedicalCase.case_number == data["case_number"]))
            case = r.scalar_one_or_none()
            if case:
                for key, value in data.items():
                    setattr(case, key, value)
                print(f"更新医案 {data['case_number']} {data['case_title']}")
            else:
                session.add(MedicalCase(**data))
                print(f"新增医案 {data['case_number']} {data['case_title']}")
        await session.commit()
        print("\n✅ 医案述评录入完成。")


if __name__ == "__main__":
    asyncio.run(main())
