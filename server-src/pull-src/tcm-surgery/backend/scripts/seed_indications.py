async def seed() -> None:
    await init_db()
    async with SessionLocal() as db:
        result = await db.execute(
            select(Formula).where((Formula.indication.is_(None)) | (Formula.indication == ""))
        )
        formulas = list(result.scalars().all())
        updated = 0
        for f in formulas:
            ind = INDICATIONS.get(f.name)
            if ind:
                f.indication = ind
                updated += 1
        await db.commit()
    print(f"✅ 适应证回填完成: 更新 {updated} 首")


if __name__ == "__main__":
    asyncio.run(seed())
