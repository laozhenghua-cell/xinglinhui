async def seed() -> None:
    await init_db()
    async with SessionLocal() as db:
        existing = {n: f for n, f in (await db.execute(select(Formula.name, Formula))).all()}
        added = 0
        updated = 0
        for name, comp, func, ind, usage, usage_type, domain in FORMULAS:
            contraindications = build_warnings(comp, ind, usage_type)
            toxicity = classify_toxicity(comp, usage_type)
            if name in existing:
                f = existing[name]
                f.composition = comp
                f.function = func
                f.indication = ind
                f.usage_type = usage_type
                f.usage = usage
                f.domain = domain
                f.contraindications = contraindications
                f.toxicity = toxicity
                f.source = "《红蓼山馆医集》"
                updated += 1
            else:
                db.add(Formula(
                    name=name,
                    source="《红蓼山馆医集》",
                    composition=comp,
                    function=func,
                    indication=ind,
                    method="伤科" if domain == "骨伤" else usage_type,
                    usage_type=usage_type,
                    usage=usage,
                    contraindications=contraindications,
                    toxicity=toxicity,
                    domain=domain,
                ))
                added += 1
        await db.flush()

        # 丹药配服规则(幂等:先清旧的张觉人配服规则)
        await db.execute(delete(TreatmentRule).where(TreatmentRule.note.like("%张觉人经验丹%")))
        dname_to_id = {n: i for i, n in (await db.execute(select(Disease.id, Disease.name))).all()}
        syn_to_id = {n: i for i, n in (await db.execute(select(Syndrome.id, Syndrome.name))).all()}
        fname_to_id = {n: i for i, n in (await db.execute(select(Formula.id, Formula.name))).all()}
        rules_added = 0
        for dname, syn_name, stage, fname, external, note in DAN_PEIFU_RULES:
            if dname in dname_to_id and syn_name in syn_to_id and fname in fname_to_id:
                db.add(TreatmentRule(
                    disease_id=dname_to_id[dname],
                    stage=stage,
                    syndrome_id=syn_to_id[syn_name],
                    internal_formula_id=fname_to_id[fname],
                    external_treatment=external,
                    nursing="忌食发物,保持患部清洁;丹药含马钱子,须控量、孕妇忌服。",
                    note=note,
                    is_specific=True,
                ))
                rules_added += 1
        await db.commit()
    print(f"✅ 红蓼山馆方剂录入完成: 新增 {added} 首 / 更新 {updated} 首 + 丹药配服规则 {rules_added} 条")


if __name__ == "__main__":
    asyncio.run(seed())
