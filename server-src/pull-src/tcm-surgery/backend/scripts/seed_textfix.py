async def seed() -> None:
    await init_db()
    async with SessionLocal() as db:
        formulas = list((await db.execute(select(Formula))).scalars().all())
        herb_fixed = func_fixed = refine_fixed = 0
        for f in formulas:
            for a, b in HERB_FIX.items():
                if f.composition and a in f.composition:
                    f.composition = f.composition.replace(a, b)
                    herb_fixed += 1
                if f.dosage and a in f.dosage:
                    f.dosage = f.dosage.replace(a, b)
            if f.name in FUNCTION_OVERRIDES and f.function == "调和气血":
                f.function = FUNCTION_OVERRIDES[f.name]
                func_fixed += 1
            elif f.name in GENERIC_REFINE and f.function == GENERIC_REFINE[f.name]:
                pass  # 已精化
            elif f.name in GENERIC_REFINE and f.function in ("消肿散结", "生肌收口", "提脓拔毒"):
                f.function = GENERIC_REFINE[f.name]
                refine_fixed += 1
        await db.commit()
    print(f"✅ 文字勘误完成: 药名还原/错字 {herb_fixed} 处 / 功效修正 {func_fixed} 首 / 功效精化 {refine_fixed} 首")


if __name__ == "__main__":
    asyncio.run(seed())
