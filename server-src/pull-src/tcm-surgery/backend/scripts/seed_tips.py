async def seed() -> None:
    await init_db()
    async with SessionLocal() as db:
        await db.execute(delete(ClinicalTip))
        for category, content in TIPS:
            db.add(ClinicalTip(category=category, content=content, source=""))
        await db.commit()
    print(f"✅ 临证心法录入完成: {len(TIPS)} 条")


if __name__ == "__main__":
    asyncio.run(seed())
